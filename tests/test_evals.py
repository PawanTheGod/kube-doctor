def test_scoring_flags_a_wrong_category() -> None:
    """A correct-but-differently-ranked answer loses the top-1 point."""
    import dataclasses

    from kube_doctor.pipeline import PipelineResult
    from kube_doctor.schema import Category, Cause, Confidence, Diagnosis

    diagnosis = Diagnosis(
        summary="Something about the pod.",
        causes=[
            Cause(
                category=Category.PROBE_FAILURE,
                title="t",
                confidence=Confidence.LOW,
                evidence=["e"],
            ),
            Cause(
                category=Category.OOM_KILLED, title="t", confidence=Confidence.LOW, evidence=["e"]
            ),
        ],
    )
    result = PipelineResult(diagnosis=diagnosis, model_id="m")
    payload = {
        "name": "unit-case",
        "screenshot": Path("x"),
        "logs": None,
        "expected": {
            "category": "oom_killed",
            "must_mention": ["OOMKilled"],
            "forbidden_claims": [],
        },
    }
    scored = run_evals.score_case(payload, result)
    assert not scored.category_correct

    assert scored.top3_hit
    assert scored.passed is False
    assert dataclasses.is_dataclass(scored)


def test_scoring_detects_invented_names() -> None:
    """A resource name absent from the inputs is flagged as a hallucination."""
    from kube_doctor.pipeline import PipelineResult
    from kube_doctor.schema import Category, Cause, Confidence, Diagnosis

    diagnosis = Diagnosis(
        summary="The pod ghost-worker-7d4 is failing.",
        causes=[
            Cause(
                category=Category.UNKNOWN,
                title="ghost-worker-7d4 is unhealthy",
                confidence=Confidence.LOW,
                evidence=["visible evidence"],
            )
        ],
    )
    payload = {
        "name": "unit-case",
        "screenshot": Path("x"),
        "logs": None,
        "expected": {"category": "unknown", "must_mention": [], "forbidden_claims": []},
    }
    scored = run_evals.score_case(payload, PipelineResult(diagnosis=diagnosis, model_id="m"))
    assert "ghost-worker-7d4" in scored.hallucinated


