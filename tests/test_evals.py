"""Tests for the eval harness, using the offline scripted backend."""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
EVALS = ROOT / "evals"
FIXTURES = EVALS / "fixtures"


def load_module() -> object:
    """Import ``evals/run_evals.py`` as a module, since evals is not a package."""
    path = EVALS / "run_evals.py"
    spec = importlib.util.spec_from_file_location("run_evals", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["run_evals"] = module
    spec.loader.exec_module(module)
    return module


run_evals = load_module()

requires_fixtures = pytest.mark.skipif(
    not FIXTURES.is_dir() or not any(FIXTURES.iterdir()),
    reason="fixtures are generated by evals/make_fixtures.py",
)


