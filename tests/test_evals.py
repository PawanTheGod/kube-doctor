def fallback_scripted_backend() -> type:
    """Build a scripted backend that reports a fallback as its answering model."""

    class FallbackScriptedBackend(run_evals.ScriptedBackend):  # type: ignore[misc, name-defined]
        """Answers with the scripted reply, but reports a different model id."""

        @property
        def model_id(self) -> str:
            return "gemma-3-27b-it"

        @property
        def primary_model_id(self) -> str:
            return "gemma-4-31b-it"

        @property
        def used_fallback(self) -> bool:
            return True

    return FallbackScriptedBackend


@requires_fixtures
def test_fallback_run_refuses_to_write_results(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A run that needed the fallback is reported but never published."""
    monkeypatch.setattr(run_evals, "ScriptedBackend", fallback_scripted_backend())
    output = tmp_path / "results.md"
    exit_code = run_evals.main(
        [
            "--backend",
            "fake",
            "--threshold",
            "1.0",
            "--output",
            str(output),
        ]
    )
    assert exit_code == 1
    assert not output.exists(), "fallback numbers must not reach the published file"


@requires_fixtures
def test_fallback_run_explains_the_refusal(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """The refusal names the offending cases, models, and the next step."""
    monkeypatch.setattr(run_evals, "ScriptedBackend", fallback_scripted_backend())
    output = tmp_path / "results.md"
    run_evals.main(["--backend", "fake", "--threshold", "0.0", "--output", str(output)])
    printed = capsys.readouterr()
    assert "Refusing to write the report" in printed.out
    assert "gemma-3-27b-it" in printed.out
    assert "gemma-4-31b-it" in printed.out
    assert "refusing to write" in printed.err


